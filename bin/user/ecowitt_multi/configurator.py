log = logging.getLogger(__name__)

STANZA = """
[EcowittMulti]
    # This section is for the Ecowitt Multi-Gateway driver (weewx-ecowitt-multi).
    driver = user.ecowitt_multi

    # sources in priority order (best first); default: order of [[sources]]
    source_priority = gw1

    # seconds between two polls
    poll_interval = 20

    # rain gauge used for 'rain' and 'rainRate': tipping or piezo
    rain_source = tipping

    # fields not in the sensor catalog: pass (as ecowitt_<key>), log or ignore
    unknown_fields = log

    # after an outage restart the engine so that WeeWX fetches the missing records
    # from the SD card / Ecowitt.net: restart or none
    gap_mode = restart
    max_catchup_days = 7

    [[sources]]
        [[[gw1]]]
            type = http
            host = 192.168.1.10
            # history = auto | sd | cloud | none
            history = auto

    # per field priorities, e.g. outTemp = gw2, gw1  or  soil* = gw2
    [[priority]]
"""


class EcowittMultiConfEditor(weewx.drivers.AbstractConfEditor):

    @property
    def default_stanza(self):
        return STANZA

    def prompt_for_settings(self):
        settings = {}
        print('Ecowitt Multi-Gateway: configure the first gateway (add more in weewx.conf).')
        settings['host'] = self._prompt('host', '192.168.1.10')
        settings['history'] = self._prompt('history', 'auto', ['auto', 'sd', 'cloud', 'none'])
        settings['rain_source'] = self._prompt('rain_source', 'tipping', ['tipping', 'piezo'])
        return settings

    def modify_config(self, config_dict):
        print('Setting record_generation to software.')
        config_dict.setdefault('StdArchive', {})['record_generation'] = 'software'
        section = config_dict.get('EcowittMulti')
        if section is not None and section.get('host'):
            gw1 = section.setdefault('sources', {}).setdefault('gw1', {})
            gw1['type'] = gw1.get('type', 'http')
            gw1['host'] = section.pop('host')
            if 'history' in section:
                gw1['history'] = section.pop('history')


def mqttsubscribe_stanza(catalog, topic='ecowitt/#', live_map=None):
    """An MQTTSubscribe [[topics]] template for the native gateway MQTT export (see README)."""
    live_map = live_map or catalog.live_map
    inverse = {key: name for name, key in live_map.items()}
    for name, keys in catalog.counters.items():
        for key in keys:
            inverse.setdefault(key, name)
    lines = ['# generated by weewx-ecowitt-multi, catalog ' + catalog.version,
             '# counters (rain totals) need contains_total = true', '[[topics]]',
             '    unit_system = US', f'    [[[{topic}]]]', '        [[[[message]]]]', '            type = json']
    for proto in sorted(catalog.protocol_map):
        canonical, unit = catalog.protocol_map[proto][0], catalog.protocol_map[proto][1]
        name = inverse.get(canonical)
        if not name:
            continue
        lines += [f'        [[[[{proto}]]]]', f'            name = {name}', f'            units = {unit}']
        if name in catalog.counters:
            lines.append('            contains_total = true')
    return '\n'.join(lines)


class EcowittMultiConfigurator(weewx.drivers.AbstractConfigurator):

    @property
    def description(self):
        return 'Query the Ecowitt Multi-Gateway sources, check the database schema.'

    @property
    def usage(self):
        return '%prog --help | --sources | --live-data | --dump-api | --history [--hours=N] | --sd-files | ' \
               '--unknown-fields | --export-mqttsubscribe | --check-schema | --add-columns'

    def add_options(self, parser):
        super().add_options(parser)
        parser.add_option('--sources', action='store_true', help='list the sources and their state')
        parser.add_option('--live-data', action='store_true', help='show a merged loop packet with provenance')
        parser.add_option('--dump-api', action='store_true', help='show the raw (canonical) data of every source')
        parser.add_option('--history', action='store_true', help='show the catchup records of the last hours')
        parser.add_option('--hours', type=int, default=3, help='hours for --history (default 3)')
        parser.add_option('--sd-files', action='store_true', help='list the SD card files of HTTP sources')
        parser.add_option('--unknown-fields', action='store_true',
                          help='show fields missing in the sensor catalog as draft catalog entries')
        parser.add_option('--export-mqttsubscribe', action='store_true',
                          help='print an MQTTSubscribe [[topics]] template from the catalog')
        parser.add_option('--check-schema', action='store_true', help='list catalog fields without a column')
        parser.add_option('--add-columns', action='store_true', help='add the missing columns')

    def do_options(self, options, parser, config_dict, prompt):
        from . import EcowittMultiDriver
        stn = dict(config_dict.get('EcowittMulti', {}))
        catalog = load_catalog(stn.get('catalog_file'))
        if options.export_mqttsubscribe:
            print(mqttsubscribe_stanza(catalog))
            return
        if options.check_schema or options.add_columns:
            self.schema(config_dict, catalog, options.add_columns, prompt)
            return
        driver = EcowittMultiDriver(config_dict=config_dict, **stn)
        try:
            now = time.time()
            if options.sources:
                driver.poll_cycle(now)
                for s in driver.sources:
                    print(f'{s.name:12} {s.kind:5} {"online" if s.online else "offline":8} '
                          f'history={s.history} fields={len(s.supplied)}')
            elif options.dump_api or options.unknown_fields:
                unknown = set()
                for s in driver.sources:
                    try:
                        data = s.poll(now)
                    except weewx.WeeWxIOError as e:
                        print(f'{s.name}: {e}')
                        continue
                    if options.dump_api:
                        print(f'--- {s.name}')
                        masked = mask_secrets(data or {})
                        for k in sorted(masked):
                            print(f'    {k} = {masked[k]}')
                    unknown |= set(catalog.unknown_keys(data or {}))
                if options.unknown_fields:
                    print(json.dumps(catalog.draft_entries(unknown), indent=2) if unknown
                          else 'all fields are in the catalog')
            elif options.live_data:
                driver.debug.merge = False
                driver.poll_cycle(now)
                record, provenance = driver.merger.merge(now)
                for k in sorted(record):
                    print(f'{k:24} {record[k]!s:>14}  <- {provenance.get(k)}')
            elif options.history:
                for rec in driver.genStartupRecords(now - options.hours * 3600):
                    print(time.strftime('%Y-%m-%d %H:%M', time.localtime(rec['dateTime'])),
                          {k: v for k, v in sorted(rec.items()) if k != 'dateTime'})
            elif options.sd_files:
                for s in driver.sources:
                    if s.kind != 'http':
                        continue
                    try:
                        info = s.device.get_sdmmc_info_data()
                        print(f'--- {s.name}: interval {info.get("info", {}).get("Interval")} min')
                        for f in info.get('file_list', []):
                            print(f"    {f.get('name')} {f.get('size', '')}")
                    except Exception as e:  # noqa: BLE001 - report and continue
                        print(f'{s.name}: no SD card info: {e}')
            else:
                parser.print_help()
        finally:
            driver.closePort()

    @staticmethod
    def schema(config_dict, catalog, add, prompt):
        import weewx.manager
        from .schema import add_columns, missing_columns, write_schema_version
        binding = config_dict.get('StdArchive', {}).get('data_binding', 'wx_binding')
        with weewx.manager.open_manager_with_config(config_dict, binding) as mgr:
            missing = missing_columns(mgr, catalog.sql_columns())
            if not missing:
                print('all catalog fields have a column')
                return
            print(f'{len(missing)} catalog fields without a column:')
            print('    ' + ', '.join(sorted(missing)))
            if not add:
                return
            if prompt and input('Add these columns (make a backup first)? (y/n) ').strip().lower() != 'y':
                print('nothing changed')
                return
            add_columns(mgr, missing)
            write_schema_version(mgr, catalog.schema_version)
            print('columns added')
